-- 02_create_staging_table.sql
-- Staging table: holds the raw EIA file exactly as it comes (every column as text),
-- so the raw data stays untouched. Cleaning happens later, in the fact table.
-- After running this, import the CSV into stg_grid with the
-- Table Data Import Wizard in MySQL Workbench.

USE texas_grid;
DROP TABLE IF EXISTS stg_grid;

CREATE TABLE stg_grid (
    `Region` VARCHAR(40),
    `UTC time` VARCHAR(40),
    `Local date` VARCHAR(40),
    `Hour` VARCHAR(40),
    `Local time` VARCHAR(40),
    `Time zone` VARCHAR(40),
    `Demand forecast` VARCHAR(40),
    `Demand` VARCHAR(40),
    `Net generation` VARCHAR(40),
    `Total interchange` VARCHAR(40),
    `Sum (NG)` VARCHAR(40),
    `NG: COL` VARCHAR(40),
    `NG: NG` VARCHAR(40),
    `NG: NUC` VARCHAR(40),
    `NG: OIL` VARCHAR(40),
    `NG: GEO` VARCHAR(40),
    `NG: WAT` VARCHAR(40),
    `NG: PS` VARCHAR(40),
    `NG: SUN` VARCHAR(40),
    `NG: SNB` VARCHAR(40),
    `NG: WND` VARCHAR(40),
    `NG: WNB` VARCHAR(40),
    `NG: BAT` VARCHAR(40),
    `NG: OES` VARCHAR(40),
    `NG: UES` VARCHAR(40),
    `NG: OTH` VARCHAR(40),
    `NG: UNK` VARCHAR(40),
    `Sum (Trade)` VARCHAR(40),
    `Sum (Imports)` VARCHAR(40),
    `Sum (Exports)` VARCHAR(40),
    `CAL` VARCHAR(40),
    `CAR` VARCHAR(40),
    `CENT` VARCHAR(40),
    `FLA` VARCHAR(40),
    `MIDA` VARCHAR(40),
    `MIDW` VARCHAR(40),
    `NE` VARCHAR(40),
    `NW` VARCHAR(40),
    `NY` VARCHAR(40),
    `SE` VARCHAR(40),
    `SW` VARCHAR(40),
    `TEN` VARCHAR(40),
    `TEX` VARCHAR(40),
    `CAN` VARCHAR(40),
    `MEX` VARCHAR(40),
    `Balance NG D TI` VARCHAR(40),
    `Balance TI Trade` VARCHAR(40),
    `Balance NG` VARCHAR(40),
    `CO2 Factor: COL` VARCHAR(40),
    `CO2 Factor: NG` VARCHAR(40),
    `CO2 Factor: OIL` VARCHAR(40),
    `Positive Gen from COL` VARCHAR(40),
    `Positive Gen from NG` VARCHAR(40),
    `Positive Gen from OIL` VARCHAR(40),
    `CO2 Emissions: COL` VARCHAR(40),
    `CO2 Emissions: NG` VARCHAR(40),
    `CO2 Emissions: OIL` VARCHAR(40),
    `CO2 Emissions: Other` VARCHAR(40),
    `CO2 Emissions Generated` VARCHAR(40),
    `CO2 Emissions Imported` VARCHAR(40),
    `CO2 Emissions Exported` VARCHAR(40),
    `CO2 Emissions Consumed` VARCHAR(40),
    `Positive Generation` VARCHAR(40),
    `Consumed Electricity` VARCHAR(40),
    `CO2 Emissions Intensity for Generated Electricity` VARCHAR(40),
    `CO2 Emissions Intensity for Consumed Electricity` VARCHAR(40)
) CHARACTER SET LATIN1;
